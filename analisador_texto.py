frase = "python é uma linguagem incrível"

print(frase) # frase original
print(frase.upper()) # frase em letras maiusculas
print(frase.lower()) # frase em letras minusculas
print(f"a frase tem {len(frase.split())} palavras")
print(f"a frase tem {len(frase.replace(' ', ''))} caracteres ")